// ---- PNG mínimo ---------------------------------------------------------
const CRC = (() => { const t = new Int32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c } return t })()
const crc32 = (buf) => { let c = -1; for (let i = 0; i < buf.length; i++) c = CRC[(c ^ buf[i]) & 0xff] ^ (c >>> 8); return (c ^ -1) >>> 0 }
const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type, "ascii"), data]); const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td)); return Buffer.concat([len, td, crc]) }
function encodePNG(width, height, rgba) {
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(width, 0); ihdr.writeUInt32BE(height, 4); ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0
  const raw = Buffer.alloc((width * 4 + 1) * height)
  for (let y = 0; y < height; y++) { raw[y * (width * 4 + 1)] = 0; rgba.copy(raw, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4) }
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", zlib.deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))])
}
const hex = (h) => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16)]

// ---- composición ------------------------------------------------------
function applyPatches(g, list) { const out = g.map((r) => r.split("")); for (const [y, x, ch] of list) if (out[y] && x >= 0 && x < 16) out[y][x] = ch; return out.map((r) => r.join("")) }

const outDir = "public/assets/characters/avatars"
fs.mkdirSync(outDir, { recursive: true })
for (const [id, pal] of Object.entries(PALETTES)) {
  const P = patches(id)
  const rows = [DOWN.map((g) => applyPatches(g, P.down)), UP.map((g) => applyPatches(g, P.up)), SIDE.map((g) => applyPatches(g, P.side))]
  const W = 64, Hh = 84
  const rgba = Buffer.alloc(W * Hh * 4)
  rows.forEach((frames, row) => frames.forEach((g, col) => {
    for (let y = 0; y < 28; y++) for (let x = 0; x < 16; x++) {
      const ch = g[y][x]; if (ch === ".") continue
      const color = pal[ch]; if (!color) continue
      const [r, gg, b] = hex(color); const i = ((row * 28 + y) * W + col * 16 + x) * 4
      rgba[i] = r; rgba[i + 1] = gg; rgba[i + 2] = b; rgba[i + 3] = 255
    }
  }))
  fs.writeFileSync(`${outDir}/${id}.png`, encodePNG(W, Hh, rgba))
  console.log("→", `${outDir}/${id}.png`)
}
